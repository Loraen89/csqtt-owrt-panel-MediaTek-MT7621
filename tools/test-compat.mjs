import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {webcrypto} from 'node:crypto';
const base=new URL('../luci-app-csqtt/package/htdocs/luci-static/resources/view/csqtt/',import.meta.url);
const ctx=vm.createContext({baseclass:{extend:v=>v},rpc:{declare:()=>()=>Promise.resolve({ok:false})},crypto:webcrypto,window:{isSecureContext:true},TextEncoder,TextDecoder,btoa,atob});
const link=vm.compileFunction(fs.readFileSync(new URL('link.js',base),'utf8'),[],{parsingContext:ctx})();
const host='connect?v=2&host=example.org&peer=46000&password=secret%26%2B%3D';
const hashA='ownerHash_0123456789',hashB='ownerHash_B123456789';
let profile=link.parseProfile(host+'&hashes='+hashA+'+'+hashB+'&power=48');
assert.equal(profile.peer,'example.org:46000');assert.equal(profile.password,'secret&+=');
assert.deepEqual(Array.from(profile.hashes),[hashA,hashB]);assert.equal(profile.workers,'48');
assert.equal(link.parseProfile(host+'&token=vk1.fixture_token=').token,'vk1.fixture_token=');
assert.equal(link.parseProfile(host+'&token=x&hashes='+hashA),null,'ambiguous credential source');
assert.equal(link.parseProfile(host+'&host=other.org'),null,'duplicate parameter');
assert.equal(link.parseProfile(host+'&power=oops'),null,'invalid worker limit');
assert.equal(link.parseProfile(host+'&hashes='+hashA+'+'+hashA),null,'duplicate hashes');
assert.equal(link.parseProfile(host+'&hashes=short'),null,'invalid hashes');
assert.equal(link.parseProfile(host+'&turn_transport=unknown'),null,'invalid transport');
assert.equal(link.parseProfile(host.replace('46000','0')),null,'invalid port');
assert.equal(link.parseProfile(host.replace('secret%26%2B%3D','%ZZ')),null,'malformed escape');
assert.equal(link.parseProfile(host.replace('example.org','2001:db8::1')).peer,'[2001:db8::1]:46000');
assert.equal(link.parseProfile('connect?v=2&host=example.org:46000&password=secret').port,'46000','old panel endpoint format');
assert.deepEqual(Array.from(link.parseProfile(host+'&hashes='+encodeURIComponent(hashA+','+hashB)).hashes),[hashA,hashB],'old comma-separated export');
const encrypted=await link.encrypt('csqtt://'+host+'&token=vk1.fixture_token=&power=40');
const decoded=await link.decode(encrypted);
assert(decoded.ok&&!decoded.plain);
assert.equal(link.parseProfile(decoded.payload).token,'vk1.fixture_token=');
const tunnel=fs.readFileSync(new URL('tunnel.js',base),'utf8');
const workerBody=tunnel.slice(tunnel.indexOf('function workersEffective('),tunnel.indexOf('return view.extend('));
const workers=new Function(workerBody+'return workersEffective;')();
for(const [requested,core,expected,exact] of [[48,'2.5.1',40],[48,'2.5.3',40],[100,'2.5.3',100],[18,'2.5.1',10],[4,'2.5.1',5],[126,'2.1.9',126],[50,'2.1.9',45],[48,'2.5.1',48,true]])assert.equal(workers(requested,core,exact),expected);
for(const entry of fs.readdirSync(base))if(entry.endsWith('.js'))new Function(fs.readFileSync(new URL(entry,base),'utf8'));
console.log('PASS: upstream v2 links, hashes/token/power, IPv6, malformed input, old exports, encrypted round-trip, three-core worker policies, LuCI syntax');
